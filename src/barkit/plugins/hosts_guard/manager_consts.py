"""hosts 管理窗的**展示常量**：来源两态、状态文案、列头、两个定宽、盯梢节拍，以及全族共用的那个日志名。

本模块**运行期零 PySide6** —— 它只认得数字与字符串。七列表头、两个下拉的共同最小宽、
搜索框定宽、盯梢的节拍与次数都在一处，改宽度不必去 UI 那一片里找。

``manager_view.py`` 拆包：正文逐字节搬移，零行为变更。
"""
from __future__ import annotations

import logging


#: 本组件全族共用的日志名（`logging_setup` 的 `%(name)s` 会写进日志文件）。
#: 写死**入口模块名**而不是 `__name__`：兄弟模块各自的 `__name__` 会把日志外观改掉。
log = logging.getLogger("barkit.plugins.hosts_guard.manager_view")


SRC_MANAGED = "managed"
SRC_EXTERNAL = "external"

STATUS_TEXT = {
    "ok": "已同步",
    "stale": "解析失败",
    "fake": "隧道虚拟地址，已拒绝",
    "idle": "待解析",
}

#: 「手动更新还没落地」在这张表里显示成什么。它与上面四种**不是同一层东西** ——
#: 那四种是解析服务给出的结论（``status``），这一格是「那条结论正在被重算」。
#: 两者可以同时成立（旧结论 ＋ 新的一轮在跑），此时显示这一格：用户按下键之后要知道的
#: 是「我这次按有没有在动」，而旧结论他刚才已经看过了。
PENDING_TEXT = "更新中…"

_COLUMNS = ["来源", "域名", "IP", "分类", "自动更新", "解析方式", "状态"]

#: 两个过滤下拉的**共同**最小宽（px）。并排的同类控件必须同宽：宽窄不同会读成两种
#: 不同性质的东西（此前「全部来源」自然宽 85、「全部分类」被单独钉 120，用户 2026-09-22
#: 上报「与其它元素不协调」）。值取最长那项（四个汉字）再留一档余量。
#: 注：下拉的**高度与样式**不在这儿管 —— 那是 ``ui_kit.ComboField`` 自带的东西
#: （此前本页的下拉是裸 ``QComboBox``，macOS 原生渲染 24px，与输入框 / 按钮都不是一回事）。
FILTER_COMBO_W = 104

#: 搜索框的定宽（px）。它**不吃 stretch**：一让它拉伸，剩下的空间全归它，在窄窗里会拉成
#: 一条与旁边按钮完全不成比例的长条（用户 2026-09-22：「输入框还太长了」）。值取得刚好
#: 放得下占位文案（「搜索域名或 IP…」），富余的宽度让给「下拉 → 动作键」之间的 stretch。
SEARCH_W = 170

#: 「更新」按下之后的盯梢节拍与次数（毫秒 / 次）。它不是后台轮询：**只在这一个动作的
#: 窗口内跑**（服务把 ``pending`` 划掉、或次数用尽即停），且每次只重画那几格文本。
#: 取值依据：一条域名的 DoH 查询通常不到 1 秒，``method=auto`` 整条降级链走完最坏
#: 20 秒 —— 故 12 次 × 0.4 秒 ≈ 5 秒是「绝大多数情况下够、又不会让用户干等」的位置；
#: 超时如实说超时（服务那边仍在跑，结论晚些会自己出现）。
_REFRESH_POLL_MS = 400
_REFRESH_POLLS = 12
